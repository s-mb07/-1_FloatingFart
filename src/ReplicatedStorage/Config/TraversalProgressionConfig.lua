--!strict
--[[
	@module TraversalProgressionConfig
	@description Traversal level / XP / length progression. Shared (server
	AND client): the server enforces it, the HUD only displays it.

	THE MODEL
	  - Every player starts at level 1 with 0 XP and `StartLength` studs of
	    real reach; each level adds `LengthPerLevel`. Level 0 does not exist.
	    A rebirth (RebirthConfig) resets level to 1 and XP to 0, and raises
	    the XP multiplier (see TraversalProgressionService.GetXPPerSecond).
	  - Stored XP is the TOTAL earned since the last rebirth ("fake length"
	    in the HUD). The level is stored separately; the total needed to leave level
	    N is the sum of the costs of levels 1..N (`GetNextThreshold`).

	THE XP CURVE is a set of TIERS: `{ level, XP cost of that level }`
	anchors. Only the anchors are data; the levels between two anchors are
	generated by `costOf` (slow early in the tier, faster late, then the next
	tier starts a new, slower stretch). To rebalance: edit a tier. To raise
	the level cap: add tiers and bump `MaxLevel` -- no code change.
]]

local TraversalProgressionConfig = {
	--- Real reach (studs) at level 1.
	StartLength = 35,
	--- Real reach added per level.
	LengthPerLevel = 7,
	--- Level cap. No next threshold exists at this level.
	MaxLevel = 150,

	--- { level, XP needed to pass THAT level }. Ascending in both fields; the
	--- first is level 1, the last is MaxLevel.
	Tiers = {
		{ 1, 17 },
		{ 10, 24 },
		{ 20, 54 },
		{ 30, 169 },
		{ 40, 613 },
		{ 50, 2300 },
		{ 60, 8000 },
		{ 70, 34600 },
		{ 80, 133600 },
		{ 90, 500600 },
		{ 100, 2000000 },
		{ 110, 7000000 },
		{ 120, 24000000 },
		{ 130, 85000000 },
		{ 140, 300000000 },
		{ 150, 1000000000 },
	} :: { { number } },
}

--- XP cost of `level`: linear anchors, eased (t^2) between them.
local function costOf(level: number): number
	local tiers = TraversalProgressionConfig.Tiers
	for i = 1, #tiers - 1 do
		local lowLevel, lowCost = tiers[i][1], tiers[i][2]
		local highLevel, highCost = tiers[i + 1][1], tiers[i + 1][2]
		if level <= highLevel then
			local t = (level - lowLevel) / (highLevel - lowLevel)
			return math.round(lowCost + (highCost - lowCost) * t * t)
		end
	end
	return tiers[#tiers][2]
end

-- cumulative[N] = total XP needed to leave level N.
local cumulative: { number } = {}
local function build(): ()
	table.clear(cumulative)
	local total = 0
	for level = 1, TraversalProgressionConfig.MaxLevel do
		total += costOf(level)
		cumulative[level] = total
	end
end
build()

--- Real reach (studs) at `level`.
function TraversalProgressionConfig.GetMaxLength(level: number): number
	return TraversalProgressionConfig.StartLength
		+ TraversalProgressionConfig.LengthPerLevel
			* (math.clamp(level, 1, TraversalProgressionConfig.MaxLevel) - 1)
end

--- XP needed to pass `level` on its own (nil outside 1..MaxLevel).
function TraversalProgressionConfig.GetLevelCost(level: number): number?
	if level < 1 or level > TraversalProgressionConfig.MaxLevel then
		return nil
	end
	return costOf(level)
end

--- TOTAL XP needed to leave `level`; nil at the cap (or for a nonsensical
--- level) -- there is nothing left to reach.
function TraversalProgressionConfig.GetNextThreshold(level: number): number?
	if type(level) ~= "number" or level ~= level or level < 1 then
		return nil
	end
	if level >= TraversalProgressionConfig.MaxLevel then
		return nil
	end
	return cumulative[level]
end

--- True when at least one level-up exists.
function TraversalProgressionConfig.HasThresholds(): boolean
	return TraversalProgressionConfig.MaxLevel > 1
end

--- Sanity check run once at service start.
--- @return boolean, string? -- ok, reason
function TraversalProgressionConfig.Validate(): (boolean, string?)
	local tiers = TraversalProgressionConfig.Tiers
	if #tiers < 2 or tiers[1][1] ~= 1 then
		return false, "Tiers must start at level 1 and hold at least 2 anchors"
	end
	if tiers[#tiers][1] < TraversalProgressionConfig.MaxLevel then
		return false, "last tier must reach MaxLevel"
	end
	for i = 2, #tiers do
		if tiers[i][1] <= tiers[i - 1][1] or tiers[i][2] < tiers[i - 1][2] then
			return false, "Tiers must be ascending in level and XP cost"
		end
	end
	return true
end

return TraversalProgressionConfig
